const today = new Date()

function iso(offset: number) {
  return format(addDays(today, offset), 'yyyy-MM-dd')
}

function stamp(offsetDays: number, time = '10:00') {
  return `${iso(offsetDays)}T${time}:00`
}

let seq = 100

function nextId(prefix: string) {
  seq += 1
  return `${prefix}_${seq}`
}


function booking(partial: Omit<Booking, 'createdAt' | 'updatedAt'> & { createdOffset?: number }): Booking {
  const { createdOffset = -4, ...rest } = partial
  const createdAt = stamp(createdOffset, '09:20')
  return { ...rest, createdAt, updatedAt: createdAt }
}

